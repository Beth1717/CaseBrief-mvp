  await page.getByRole('button',{name:'Close CRI details'}).click();
  await page.evaluate(()=>{data.documents.forEach(d=>d.reviewed=true);save();data.documents.find(d=>d.id==='S02').excerpt+=' Revised after review';showView('dashboard')});
  assert.equal(await page.evaluate(()=>pilotCRI().components.workControl.value),92);
  assert.equal(await page.evaluate(()=>data.documents.find(d=>d.id==='S02').reviewed),false);
  await page.evaluate(()=>{data.documents.forEach(d=>d.reviewed=true);ensurePilotFindings();window.removedSource=structuredClone(data.documents.find(d=>d.id==='S02'));data.documents=data.documents.filter(d=>d.id!=='S02');ensurePilotFindings()});
