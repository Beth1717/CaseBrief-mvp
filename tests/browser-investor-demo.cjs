  await page.locator('input[name=releaseSource][value=S02]').check();
  await page.getByRole('button',{name:'Save read-only release'}).click();
  await page.getByRole('button',{name:'Preview family brief'}).click();
  const preview=await page.locator('#detailRoot').innerText();
  assert.match(preview,/Incident report|Camera transcript/);
  assert.doesNotMatch(preview,/Internal strategy note|Restricted attorney work note|Attorney review notes/);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Family access',exact:true}).click();
  await page.getByRole('button',{name:'Revoke access'}).click();
  await page.getByRole('button',{name:'Preview family brief'}).click();
  assert.match(await page.locator('#detailRoot').innerText(),/No sources are currently released/);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Next step',exact:true}).click();
  assert.match(await page.locator('#app').innerText(),/Draft Generated|Share Revoked|Review status changed/i);
  await page.getByRole('button',{name:'Finish walkthrough'}).click();
  await page.evaluate(()=>showView('dashboard'));
