  assert.match(await page.locator('#detailRoot').innerText(),/21:09:30/);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Next step',exact:true}).click();
  await page.getByRole('button',{name:'Confirm',exact:true}).first().click();
  await page.locator('#decisionReason').fill('Compared S01, S02 and S03. Clock accuracy still needs investigation.');
  await page.getByRole('button',{name:'Save decision',exact:true}).click();
  assert.equal(await page.evaluate(()=>score()),63);
  await page.getByRole('button',{name:'Next step',exact:true}).click();
  await page.locator('#aiPrompt').fill('What records are missing?');
  await page.getByRole('button',{name:'Ask CaseBrief AI',exact:true}).last().click();
  assert.match(await page.locator('.bubble.ai').last().innerText(),/LAB-E02|CUSTODY-E01/);
  await page.getByRole('button',{name:'Next step',exact:true}).click();
  await page.getByRole('button',{name:'Generate internal review memo'}).click();
  await page.locator('.draft-list-button').click();
  await page.getByRole('button',{name:'Edit document'}).click();
  await page.locator('#draftEditor').fill('Attorney review notes <script>plain text only</script>');
  await page.getByRole('button',{name:'Save new version'}).click();
  assert.equal(await page.evaluate(()=>data.drafts.at(-1).versions.length),1);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Next step',exact:true}).click();
  await page.getByRole('button',{name:'Family access',exact:true}).click();
